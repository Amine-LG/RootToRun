"""Write docs/COVERAGE.md: each planned topic with the material that covers it and a status computed from that
material (never typed by hand).

    .venv/bin/python scripts/coverage.py          # write docs/COVERAGE.md
    .venv/bin/python scripts/coverage.py --check  # exit 1 if coverage.yaml names something that does not exist

Status of a topic:
  missing        no material
  explained      lessons only (reading and checks; no hands-on practice)
  implemented    hands-on material exists, but some of it has no passing recording on a real cluster
  live-verified  every lab, incident and challenge listed for it has a passing recording on a real cluster, and its
                 grader failed the starting state and passed the reference solution
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from academy import config, curriculum, labs  # noqa: E402


def main() -> int:
    plan = yaml.safe_load((config.content_dir("en") / "coverage.yaml").read_text(encoding="utf-8"))
    cur = curriculum.load("en")
    all_labs = labs.load("en")
    unknown = [i for tr in plan for tp in tr["topics"] for i in tp["items"] if i not in cur["lessons"] and i not in all_labs]
    listed = {i for tr in plan for tp in tr["topics"] for i in tp["items"]}
    absent = [i for i in [*cur["lessons"], *all_labs] if i not in listed]
    if "--check" in sys.argv:
        print("\n".join([*(f"unknown: {i}" for i in unknown), *(f"not in any topic: {i}" for i in absent)]) or "ok")
        return 1 if unknown or absent else 0
    if unknown:
        raise SystemExit(f"coverage.yaml names unknown items: {unknown}")

    def lab_evidence(lid: str) -> tuple[bool, str]:
        rec = labs.recording(lid) or {}
        lab = all_labs[lid]
        current = rec.get("lab_hash") == labs.lab_hash(lab)
        ok = bool(rec.get("ok")) and current
        before = (rec.get("verify_before") or {}).get("verdict")
        after = (rec.get("verify_after") or {}).get("verdict")
        if lab.kind in ("incident", "challenge"):
            # The starting state is evidence only if the grader demonstrably rejected it: at least one check ran and
            # failed. A check that could not run proves nothing, though it may be inherent to the breakage (a pod
            # that never starts cannot be connected to) as long as other checks really fail.
            baseline = (rec.get("verify_before") or {}).get("results") or []
            rejected = any(r.get("status") == "fail" for r in baseline)
            if lab.kind == "challenge":  # a challenge starts from a working, checkable state: every check must run
                rejected = rejected and not any(r.get("status") == "error" for r in baseline)
            ok = ok and rejected and before != "verified" and after == "verified"
        elif not lab.checks:
            ok = False  # commands ran on a real cluster, but nothing graded the result
            return ok, f"~ {lid} (commands recorded on {(rec.get('cluster') or {}).get('openshift', '?')}, no grader)"
        trials = rec.get("trials") or []
        t = f", {sum(1 for x in trials if x.get('ok'))}/{len(trials)} grader trials" if trials else ""
        when = f"{(rec.get('cluster') or {}).get('openshift', '?')} {str(rec.get('recorded_at', ''))[:10]}" if rec else "never recorded"
        return ok, f"{'✓' if ok else '✗'} {lid} ({when}{t})"

    diag_items = [it for g in cur.get("diagnostics", {}).values() for it in g.items]

    lines = ["# Curriculum coverage matrix", "",
             "Generated by `scripts/coverage.py` from `content/en/coverage.yaml`, the lessons and the recordings. Do not edit by hand.",
             "", "Status: **missing** (nothing), **explained** (lessons and checks only), **implemented** (hands-on material, not all of it",
             "passing on a real cluster), **live-verified** (every listed lab, incident and challenge has a current passing recording;",
             "incident and challenge graders failed the starting state and passed the reference solution). Recordings come from",
             "OpenShift Local (single node); live-verified does not mean verified on a multi-node or production cluster.",
             "**partly live-verified**: the listed practice passes, but part of the topic (see Gap) has no practice.", "",
             "Columns: **Visual** lists lessons with a diagram or interactive model. **Checks** counts lesson check and prediction questions; **Diagnostic** counts track-diagnostic",
             "items that point at the topic. ✓ marks a lab, incident or challenge with a current passing recording on OpenShift",
             "Local (graded by its checks); ~ marks commands recorded without a grader; ✗ marks no current passing recording.",
             "**Environment limit** is what the single-node course cluster cannot show; **Gap** is work not done yet.", ""]
    totals: dict[str, int] = {}
    for tr in plan:
        lines += [f"## {tr['track']}", "", "| Topic | Explanation (lessons) | Visual | Checks | Diagnostic | Guided labs | Independent (challenges, incidents) | Status | Environment limit | Gap |", "|---|---|---|---|---|---|---|---|---|---|"]
        for tp in tr["topics"]:
            ls = [cur["lessons"][i] for i in tp["items"] if i in cur["lessons"]]
            guided = [i for i in tp["items"] if i in all_labs and all_labs[i].kind == "lab"]
            indep = [i for i in tp["items"] if i in all_labs and all_labs[i].kind in ("incident", "challenge")]
            ev = [lab_evidence(i) for i in guided + indep]
            checks = sum(len(l.predict) for l in ls)
            inter = [l.id for l in ls if l.diagram or l.simulator]
            if not ls and not ev:
                status = "missing"
            elif not ev:
                status = "explained"
            elif all(ok for ok, _ in ev):
                status = "partly live-verified" if tp.get("gap") or tp.get("limit") else "live-verified"  # practice passes, part of the topic is not practised
            else:
                status = "implemented"
            if tr["track"].startswith("Advanced") and status != "missing":
                status = "explained" if not ev else status
            totals[status] = totals.get(status, 0) + 1
            fmt = lambda xs: "<br>".join(xs) or "—"  # noqa: E731
            ndiag = sum(1 for it in diag_items if set(it.targets) & set(tp["items"]))
            lines.append(f"| {tp['title']} | {fmt([f'{l.id}' for l in ls])} | {fmt(inter)} | {checks or '—'} | {ndiag or '—'} | "
                         f"{fmt([e for (ok, e), i in zip(ev, guided + indep) if i in guided])} | "
                         f"{fmt([e for (ok, e), i in zip(ev, guided + indep) if i in indep])} | **{status}** | {tp.get('limit', '')} | {tp.get('gap', '')} |")
        lines.append("")
    lines += ["## Summary", "", " · ".join(f"{k}: {v}" for k, v in sorted(totals.items())), "",
              f"Lessons: {len(cur['lessons'])}, check questions: {sum(len(l.predict) for l in cur['lessons'].values())}, "
              f"lessons with an explain-it-in-your-own-words step: {sum(1 for l in cur['lessons'].values() if l.explain or any(st.kind == 'reflect' for st in l.flow))}, "
              f"guided labs: {sum(1 for l in all_labs.values() if l.kind == 'lab')}, incidents: {sum(1 for l in all_labs.values() if l.kind == 'incident')}, "
              f"challenges: {sum(1 for l in all_labs.values() if l.kind == 'challenge')}, diagnostic items: {len(diag_items)} in {len(cur.get("diagnostics", {}))} tracks.", ""]
    (ROOT / "docs" / "COVERAGE.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    write_lab_table(all_labs)
    print("wrote docs/COVERAGE.md:", totals)
    return 0


NEEDS = {"project-create": "a new project", "admin": "cluster-admin", "reader": "cluster reader", "routes": "Routes",
         "dynamic-storage": "dynamic storage", "olm": "OLM", "crc": "OpenShift Local", "cluster-objects": "cluster objects (admin)"}


def needs_text(lab) -> str:
    """What the lab needs, derived from its content like the app's preflight (environment.lab_requirements)."""
    from academy import environment  # imported here: only the lab table needs it

    reqs = environment.lab_requirements(lab)
    words = [NEEDS.get(r, r) for r in reqs if r != "project-create" and not (r == "cluster-objects" and "admin" in reqs)]
    if lab.elevated_setup:
        words = [w + " (elevated setup)" if w == "cluster-admin" else w for w in words]
    return ", ".join(["project admin", *words])


def write_lab_table(all_labs) -> None:
    """docs/LAB-VERIFICATION.md: every executable lab, incident and challenge with its recorded live evidence."""
    out = ["# Lab verification", "", "Generated by `scripts/coverage.py` from `content/recordings/`. A recording is made by `scripts/record.py`, which",
           "runs every command on a real cluster through the same policy and runner as the app, grades the starting state, runs the",
           "steps or the reference solution, grades again, runs grader trials (challenges), and verifies cleanup. **Current** means",
           "the lab has not changed since it was recorded.", "",
           "| Id | Kind | Title | Project | Needs | Recorded on | Current | Start graded | End graded | Grader trials | Cleanup | Result |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for lid in sorted(all_labs, key=lambda i: (all_labs[i].kind, i)):
        lab = all_labs[lid]
        rec = labs.recording(lid) or {}
        cur = rec.get("lab_hash") == labs.lab_hash(lab)
        trials = rec.get("trials") or []
        tr = f"{sum(1 for t in trials if t.get('ok'))}/{len(trials)}" if trials else "—"
        needs = needs_text(lab)
        when = f"OpenShift {(rec.get('cluster') or {}).get('openshift', '?')}, {str(rec.get('recorded_at', ''))[:10]}" if rec else "never"
        out.append(f"| `{lid}` | {lab.kind} | {lab.title} | `{lab.namespace}` | {needs} | {when} | {'yes' if cur else 'NO'} | "
                   f"{(rec.get('verify_before') or {}).get('verdict', '—')} | {(rec.get('verify_after') or {}).get('verdict', '—')} | {tr} | "
                   f"{(rec.get('cleanup') or {}).get('state', '—')} | {'pass' if rec.get('ok') and cur else 'FAIL' if rec else 'not recorded'} |")
    ok = sum(1 for lid, lab in all_labs.items() if (labs.recording(lid) or {}).get("ok") and (labs.recording(lid) or {}).get("lab_hash") == labs.lab_hash(lab))
    out += ["", f"{ok} of {len(all_labs)} pass with a current recording.", ""]
    (ROOT / "docs" / "LAB-VERIFICATION.md").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    sys.exit(main())
